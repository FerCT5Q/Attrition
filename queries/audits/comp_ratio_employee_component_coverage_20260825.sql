WITH eligible AS (
  SELECT
    fis_mo_end_dt,
    annual_base_pay,
    base_pay_rate,
    total_base_pay_amount,
    fte_annual_base_pay,
    base_pay_frequency,
    fte_annual_base_pay_currency_code,
    compensation_grade,
    compensation_grade_old,
    compensation_grade_profile,
    cf_ee_rf360_comp_grade,
    fte,
    std_hours,
    full_or_part_time,
    country,
    region,
    labor_market,
    job_code,
    job_title,
    job_family,
    job_level_primary_position,
    level_grouped,
    management_level,
    company_id,
    company_name
  FROM hrda.post_hire_monthly_worker_dtls
  WHERE worker_type = 'Employee'
    AND employee_type = 'Regular'
    AND active_status = 1
    AND fis_mo_end_dt <= DATE '2026-08-25'
), latest AS (
  SELECT MAX(fis_mo_end_dt) AS snapshot_date
  FROM eligible
), summary AS (
  SELECT
    COUNT(*) AS eligible_rows,
    COUNT(DISTINCT fis_mo_end_dt) AS snapshots_checked,
    COUNT(CASE WHEN annual_base_pay IS NOT NULL THEN 1 END) AS annual_base_pay_rows,
    COUNT(CASE WHEN base_pay_rate IS NOT NULL THEN 1 END) AS base_pay_rate_rows,
    COUNT(CASE WHEN total_base_pay_amount IS NOT NULL THEN 1 END) AS total_base_pay_amount_rows,
    COUNT(CASE WHEN fte_annual_base_pay IS NOT NULL THEN 1 END) AS fte_annual_base_pay_rows,
    COUNT(CASE WHEN base_pay_frequency IS NOT NULL THEN 1 END) AS base_pay_frequency_rows,
    COUNT(CASE WHEN fte_annual_base_pay_currency_code IS NOT NULL THEN 1 END) AS currency_rows,
    COUNT(CASE WHEN compensation_grade IS NOT NULL THEN 1 END) AS compensation_grade_rows,
    COUNT(CASE WHEN compensation_grade_old IS NOT NULL THEN 1 END) AS compensation_grade_old_rows,
    COUNT(CASE WHEN compensation_grade_profile IS NOT NULL THEN 1 END) AS compensation_grade_profile_rows,
    COUNT(CASE WHEN cf_ee_rf360_comp_grade IS NOT NULL THEN 1 END) AS cf_ee_rf360_comp_grade_rows,
    COUNT(CASE WHEN fte IS NOT NULL THEN 1 END) AS fte_rows,
    COUNT(CASE WHEN std_hours IS NOT NULL THEN 1 END) AS std_hours_rows,
    COUNT(CASE WHEN full_or_part_time IS NOT NULL THEN 1 END) AS full_or_part_time_rows,
    COUNT(CASE WHEN country IS NOT NULL THEN 1 END) AS country_rows,
    COUNT(CASE WHEN region IS NOT NULL THEN 1 END) AS region_rows,
    COUNT(CASE WHEN labor_market IS NOT NULL THEN 1 END) AS labor_market_rows,
    COUNT(CASE WHEN job_code IS NOT NULL THEN 1 END) AS job_code_rows,
    COUNT(CASE WHEN job_title IS NOT NULL THEN 1 END) AS job_title_rows,
    COUNT(CASE WHEN job_family IS NOT NULL THEN 1 END) AS job_family_rows,
    COUNT(CASE WHEN job_level_primary_position IS NOT NULL THEN 1 END) AS job_level_primary_position_rows,
    COUNT(CASE WHEN level_grouped IS NOT NULL THEN 1 END) AS level_grouped_rows,
    COUNT(CASE WHEN management_level IS NOT NULL THEN 1 END) AS management_level_rows,
    COUNT(CASE WHEN company_id IS NOT NULL THEN 1 END) AS company_id_rows,
    COUNT(CASE WHEN company_name IS NOT NULL THEN 1 END) AS company_name_rows
  FROM eligible
), latest_summary AS (
  SELECT
    COUNT(*) AS latest_rows,
    COUNT(CASE WHEN annual_base_pay IS NOT NULL THEN 1 END) AS latest_annual_base_pay_rows,
    COUNT(CASE WHEN base_pay_rate IS NOT NULL THEN 1 END) AS latest_base_pay_rate_rows,
    COUNT(CASE WHEN total_base_pay_amount IS NOT NULL THEN 1 END) AS latest_total_base_pay_amount_rows,
    COUNT(CASE WHEN fte_annual_base_pay IS NOT NULL THEN 1 END) AS latest_fte_annual_base_pay_rows,
    COUNT(CASE WHEN base_pay_frequency IS NOT NULL THEN 1 END) AS latest_base_pay_frequency_rows,
    COUNT(CASE WHEN fte_annual_base_pay_currency_code IS NOT NULL THEN 1 END) AS latest_currency_rows,
    COUNT(CASE WHEN compensation_grade IS NOT NULL THEN 1 END) AS latest_compensation_grade_rows,
    COUNT(CASE WHEN compensation_grade_old IS NOT NULL THEN 1 END) AS latest_compensation_grade_old_rows,
    COUNT(CASE WHEN compensation_grade_profile IS NOT NULL THEN 1 END) AS latest_compensation_grade_profile_rows,
    COUNT(CASE WHEN cf_ee_rf360_comp_grade IS NOT NULL THEN 1 END) AS latest_cf_ee_rf360_comp_grade_rows,
    COUNT(CASE WHEN fte IS NOT NULL THEN 1 END) AS latest_fte_rows,
    COUNT(CASE WHEN std_hours IS NOT NULL THEN 1 END) AS latest_std_hours_rows,
    COUNT(CASE WHEN full_or_part_time IS NOT NULL THEN 1 END) AS latest_full_or_part_time_rows,
    COUNT(CASE WHEN country IS NOT NULL THEN 1 END) AS latest_country_rows,
    COUNT(CASE WHEN region IS NOT NULL THEN 1 END) AS latest_region_rows,
    COUNT(CASE WHEN labor_market IS NOT NULL THEN 1 END) AS latest_labor_market_rows,
    COUNT(CASE WHEN job_code IS NOT NULL THEN 1 END) AS latest_job_code_rows,
    COUNT(CASE WHEN job_title IS NOT NULL THEN 1 END) AS latest_job_title_rows,
    COUNT(CASE WHEN job_family IS NOT NULL THEN 1 END) AS latest_job_family_rows,
    COUNT(CASE WHEN job_level_primary_position IS NOT NULL THEN 1 END) AS latest_job_level_primary_position_rows,
    COUNT(CASE WHEN level_grouped IS NOT NULL THEN 1 END) AS latest_level_grouped_rows,
    COUNT(CASE WHEN management_level IS NOT NULL THEN 1 END) AS latest_management_level_rows,
    COUNT(CASE WHEN company_id IS NOT NULL THEN 1 END) AS latest_company_id_rows,
    COUNT(CASE WHEN company_name IS NOT NULL THEN 1 END) AS latest_company_name_rows
  FROM eligible
  WHERE fis_mo_end_dt = (SELECT snapshot_date FROM latest)
)
SELECT
  latest.snapshot_date,
  summary.eligible_rows,
  summary.snapshots_checked,
  latest_summary.latest_rows,
  summary.annual_base_pay_rows,
  summary.base_pay_rate_rows,
  summary.total_base_pay_amount_rows,
  summary.fte_annual_base_pay_rows,
  summary.base_pay_frequency_rows,
  summary.currency_rows,
  summary.compensation_grade_rows,
  summary.compensation_grade_old_rows,
  summary.compensation_grade_profile_rows,
  summary.cf_ee_rf360_comp_grade_rows,
  summary.fte_rows,
  summary.std_hours_rows,
  summary.full_or_part_time_rows,
  summary.country_rows,
  summary.region_rows,
  summary.labor_market_rows,
  summary.job_code_rows,
  summary.job_title_rows,
  summary.job_family_rows,
  summary.job_level_primary_position_rows,
  summary.level_grouped_rows,
  summary.management_level_rows,
  summary.company_id_rows,
  summary.company_name_rows,
  latest_summary.latest_annual_base_pay_rows,
  latest_summary.latest_base_pay_rate_rows,
  latest_summary.latest_total_base_pay_amount_rows,
  latest_summary.latest_fte_annual_base_pay_rows,
  latest_summary.latest_base_pay_frequency_rows,
  latest_summary.latest_currency_rows,
  latest_summary.latest_compensation_grade_rows,
  latest_summary.latest_compensation_grade_old_rows,
  latest_summary.latest_compensation_grade_profile_rows,
  latest_summary.latest_cf_ee_rf360_comp_grade_rows,
  latest_summary.latest_fte_rows,
  latest_summary.latest_std_hours_rows,
  latest_summary.latest_full_or_part_time_rows,
  latest_summary.latest_country_rows,
  latest_summary.latest_region_rows,
  latest_summary.latest_labor_market_rows,
  latest_summary.latest_job_code_rows,
  latest_summary.latest_job_title_rows,
  latest_summary.latest_job_family_rows,
  latest_summary.latest_job_level_primary_position_rows,
  latest_summary.latest_level_grouped_rows,
  latest_summary.latest_management_level_rows,
  latest_summary.latest_company_id_rows,
  latest_summary.latest_company_name_rows
FROM summary
CROSS JOIN latest
CROSS JOIN latest_summary;
